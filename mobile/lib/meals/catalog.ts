import type { MealType, Recipe, RecipeIngredient, RecipeStep } from './types';

export type CompleteNutrition = {
  calories: number;
  proteinG: number;
  carbsG: number;
  fatG: number;
};

export type PreparationMethod = 'air-fryer' | 'one-pan' | 'oven' | 'stovetop' | 'no-cook' | 'slow-cooker';

export type CatalogRecipeIngredient = Omit<RecipeIngredient, 'quantity' | 'unit'> & {
  quantity: number;
  unit: string;
};

export type CatalogRecipeStep = Omit<RecipeStep, 'durationMinutes'> & {
  durationMinutes: number;
  ingredientIds: string[];
  cue: string;
};

export type CatalogRecipeImage =
  | { kind: 'exact'; uri: string; alt: string }
  | { kind: 'bundled'; assetKey: string; alt: string }
  | { kind: 'absent'; reason: string };

type CatalogRecipeCore = Omit<Recipe, 'source' | 'nutrition' | 'ingredients' | 'steps' | 'imageUri'> & {
  source: 'curated';
  mealType: MealType;
  nutrition: CompleteNutrition;
  ingredients: CatalogRecipeIngredient[];
  steps: CatalogRecipeStep[];
  prepMinutes: number;
  cookMinutes: number;
  preparationMethods: PreparationMethod[];
  planReady: true;
};

export type CatalogRecipe = CatalogRecipeCore &
  (
    | { image: Extract<CatalogRecipeImage, { kind: 'exact' }>; imageUri: string }
    | { image: Extract<CatalogRecipeImage, { kind: 'bundled' }>; imageUri?: never }
    | { image: Extract<CatalogRecipeImage, { kind: 'absent' }>; imageUri?: never }
  );

type IngredientInput = readonly [name: string, quantity: number, unit: string, note?: string];
type StepInput = readonly [
  text: string,
  durationMinutes: number,
  ingredientIndexes: readonly number[],
  cue: string,
];

type RecipeDefinition = {
  id: string;
  name: string;
  mealType: MealType;
  servings: number;
  description: string;
  nutrition: CompleteNutrition;
  prepMinutes: number;
  cookMinutes: number;
  ingredients: readonly IngredientInput[];
  steps: readonly StepInput[];
  substitutions: readonly string[];
  dietaryTags: readonly string[];
};

function buildRecipe(definition: RecipeDefinition): CatalogRecipe {
  const ingredients: CatalogRecipeIngredient[] = definition.ingredients.map(
    ([name, quantity, unit, note], index) => ({
      id: `${definition.id}_ingredient_${index + 1}`,
      name,
      quantity,
      unit,
      ...(note ? { note } : {}),
    }),
  );

  const steps: CatalogRecipeStep[] = definition.steps.map(
    ([text, durationMinutes, ingredientIndexes, cue], index) => ({
      id: `${definition.id}_step_${index + 1}`,
      text,
      durationMinutes,
      ingredientIds: ingredientIndexes.map((ingredientIndex) => {
        const ingredient = ingredients[ingredientIndex];
        if (!ingredient) {
          throw new Error(`${definition.id} step ${index + 1} references ingredient ${ingredientIndex}`);
        }
        return ingredient.id;
      }),
      cue,
    }),
  );

  return {
    id: definition.id,
    name: definition.name,
    source: 'curated',
    providerId: `luminary:${definition.id}:1`,
    servings: definition.servings,
    description: definition.description,
    mealType: definition.mealType,
    nutrition: definition.nutrition,
    ingredients,
    steps,
    substitutions: [...definition.substitutions],
    dietaryTags: [...definition.dietaryTags],
    prepMinutes: definition.prepMinutes,
    cookMinutes: definition.cookMinutes,
    preparationMethods: inferPreparationMethods(definition),
    planReady: true,
    image: {
      kind: 'bundled',
      assetKey: definition.id,
      alt: `${definition.name}, prepared and ready to serve`,
    },
  };
}

function inferPreparationMethods(definition: RecipeDefinition): PreparationMethod[] {
  const text = [definition.name, definition.description, ...definition.steps.map(([step]) => step)].join(' ').toLowerCase();
  const methods: PreparationMethod[] = [];
  if (/air[ -]?fry/.test(text)) methods.push('air-fryer');
  if (/slow cooker|crockpot/.test(text)) methods.push('slow-cooker');
  if (/one-pan|one pan|sheet-pan|sheet pan|single skillet/.test(text)) methods.push('one-pan');
  if (/\b(bake|baked|roast|roasted|oven|muffin)\b/.test(text)) methods.push('oven');
  if (definition.cookMinutes === 0) methods.push('no-cook');
  if (/\b(skillet|pan-sear|sauté|simmer|boil|stovetop|pot)\b/.test(text)) methods.push('stovetop');
  return methods.length ? [...new Set(methods)] : ['stovetop'];
}

